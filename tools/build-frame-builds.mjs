// Writes src/data/frame-builds.js from tools/data/reference-builds.json: what the page needs of each frame's builds, for
// the Strength and Duration a buff is cast with. Mid-video edits are left out; each frame's best-read builds come first.
//   node tools/build-frame-builds.mjs

import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const rows = JSON.parse(fs.readFileSync(path.join(ROOT, 'tools/data/reference-builds.json'), 'utf8'));

/** @type {Record<string, object[]>} */
const frames = {};
for (const r of rows) {
  if (r.edit) continue;
  (frames[r.frame] ??= []).push({ tab: r.tab, strength: r.strength, duration: Number(r.stats.split('/')[1]), reads: r.reads, ...(r.molt ? { molt: 1 } : {}), ...(r.budget ? { budget: 1 } : {}) });
}
const lines = Object.entries(frames).map(([frame, builds]) => `  ${JSON.stringify(frame)}: [\n${builds.map(b => `    ${JSON.stringify(b)},`).join('\n')}\n  ],`);
fs.writeFileSync(path.join(ROOT, 'src/data/frame-builds.js'), `// @ts-check
// Generated by tools/build-frame-builds.mjs from Brozime's builds (docs/reference-builds.md). Don't edit by hand.
// Strength and Duration are the panel's general totals; molt: it runs Molt Augmented; budget: a low-investment build.

/** @typedef {{tab: string, strength: number, duration: number, reads: number, molt?: number, budget?: number}} FrameBuild */

/** @type {Record<string, FrameBuild[]>} */
export const FRAME_BUILDS = {
${lines.join('\n')}
};
`);
console.log(Object.keys(frames).length, 'frames,', Object.values(frames).flat().length, 'builds');
