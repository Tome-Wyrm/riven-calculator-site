// Regenerates src/data/picks.js from the community Rolls & Resources sheet's main tab (recommended
// riven rolls per weapon family). Run by hand when the sheet changes:
//   node tools/build-picks.mjs
// The output is committed, so the site never fetches at runtime. The cells are kept as written;
// src/picks.js reads the shorthand.

import { readFile, writeFile } from 'node:fs/promises';
import { WEAPONS } from '../src/data/weapons.js';

const SHEET = 'https://docs.google.com/spreadsheets/d/1OQGKpWXeoPaN0Cy7mTvVZMRcwvZXgIC3EO1AIRAkwDg';
const CSV = `${SHEET}/export?format=csv&gid=0`;

/** RFC 4180 CSV: quoted fields, doubled quotes, newlines inside quotes. @param {string} s */
function parseCsv(s) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (quoted) {
      if (c === '"' && s[i + 1] === '"') { field += '"'; i++; } else if (c === '"') quoted = false; else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c !== '\r') field += c;
  }
  row.push(field);
  rows.push(row);
  return rows;
}

const tidy = (/** @type {string} */ s) => s.replace(/\s+/g, ' ').trim();

const rows = parseCsv(await (await fetch(CSV)).text());
const start = rows.findIndex(r => r[0] === 'Name');
if (start < 0) throw new Error("No 'Name' header row: has the sheet's layout changed?");

// A row starting "[Name]" opens a family; rows below it with an empty first cell are its other
// rolls ("ordered by usability"). Cells: positives in columns 1-3 (one row strays into 4-5),
// negatives in 6, notes from 7 on.
/** @type {Record<string, string[][]>} */
const picks = {};
let family = '';
for (const r of rows.slice(start + 1)) {
  // "[Vinquibus] (Melee)": a weapon whose second form takes its own riven (ours: "Vinquibus (melee)").
  const head = r[0].trim().match(/^\[(.+)\]\s*(?:\((Rifle|Melee)\))?$/);
  if (head) family = tidy(head[1]) + (head[2] === 'Melee' ? ' (melee)' : '');
  else if (r[0].trim()) { console.warn(`Skipped row: ${r.join(' | ')}`); continue; }
  const pos = r.slice(1, 6).map(tidy).filter(Boolean);
  if (!family || !pos.length) continue;
  const notes = r.slice(7).map(tidy).filter(Boolean).join(' | ');
  (picks[family] ??= []).push([pos[0] ?? '', pos[1] ?? '', pos[2] ?? '', tidy(r[6] ?? ''), notes]);
}

/** Riven family of each weapon name, from the CSV. */
const familyOf = new Map();
for (const line of (await readFile(new URL('./data/internal_names.csv', import.meta.url), 'utf8')).trim().split(/\r?\n/).slice(1)) {
  const [, name, fam] = line.slice(1, -1).split('","');
  familyOf.set(name, fam);
}

const byLower = new Map(Object.keys(picks).map(k => [k.toLowerCase(), k]));
/** @type {Record<string, string>} */
const pickFamily = {};
const used = new Set();
const missing = [];
for (const [name] of WEAPONS) {
  const fam = familyOf.get(name) ?? name;
  // The sheet names zaws and kitguns without our "(Zaw)" / "(Kitgun)" labels.
  const key = [fam, fam.replace(/ \((Zaw|Kitgun)\)$/, ''), name].map(k => byLower.get(k.toLowerCase())).find(Boolean);
  if (!key) { missing.push(name); continue; }
  used.add(key);
  if (key !== name) pickFamily[name] = key;
}
const unused = Object.keys(picks).filter(k => !used.has(k));
if (missing.length) console.warn(`Weapons with no picks (${missing.length}): ${missing.join(', ')}`);
if (unused.length) console.warn(`Sheet families matching no weapon (${unused.length}): ${unused.join(', ')}`);

const date = new Date().toISOString().slice(0, 10);
const json = (/** @type {unknown} */ v) => JSON.stringify(v);
await writeFile(new URL('../src/data/picks.js', import.meta.url), `// @ts-check
// GENERATED by tools/build-picks.mjs on ${date} from the Rolls & Resources sheet (main tab) by
// Megrim, Valkyrial and Lia, based on the original by 44Bananas: ${SHEET}
// Don't edit by hand. src/picks.js reads the shorthand.

export const PICKS_UPDATED = '${date}';
export const PICKS_SOURCE = '${SHEET}';

/**
 * Recommended rolls by riven family, best first: [positive slot 1, slot 2, slot 3, negatives, notes],
 * as written in the sheet.
 * @type {Record<string, string[][]>}
 */
export const PICKS = {
${Object.entries(picks).map(([k, v]) => `  ${json(k)}: [\n${v.map(r => `    ${json(r)},`).join('\n')}\n  ],`).join('\n')}
};

/** Weapon → its family in PICKS, where the names differ. @type {Record<string, string>} */
export const PICK_FAMILY = {
${Object.entries(pickFamily).map(([k, v]) => `  ${json(k)}: ${json(v)},`).join('\n')}
};
`);
console.log(`Wrote ${Object.keys(picks).length} families, ${WEAPONS.length - missing.length} of ${WEAPONS.length} weapons matched`);
