// Writes src/data/frame-power.js: what src/underframe.js needs to read a frame build. The frame and mod names come from
// the cached Underframe data (a link stores each as a hash of its name; game names only, nothing of Underframe's own),
// the Strength and Duration of each mod from WFCD's text at max rank.
//   node tools/build-frame-power.mjs

import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const cached = (/** @type {string} */ name) => JSON.parse(fs.readFileSync(path.join(ROOT, `tools/data/cache/${name}.json`), 'utf8'));
const unwrap = (/** @type {any} */ d) => d.data ?? d;
const underframe = unwrap(cached('underframe'));
const wfcd = /** @type {any[]} */ (Object.values(unwrap(cached('wfcd-mods'))));

/** Always on, in words the reader below doesn't take. */
const WORDED = {
  'Power Donation': { strength: -30, rank: 5 },
  'Anchored Glide': { strength: 15, rank: 5 },
  'Controlled Slide': { strength: 15, rank: 5 },
};
const LINE = /^([+-]\d+(?:\.\d+)?)% Ability (Strength|Duration)$/;

/** @type {Record<string, {strength?: number, duration?: number, rank: number}>} */
const power = { ...WORDED };
for (const m of wfcd) {
  // (Beginner and Expert are copies that never reached the game, Intensify at +55; Primed mods are Expert too, and real.)
  if (!['WARFRAME', 'AURA'].includes(m.compatName) || /Beginner/.test(m.uniqueName) || (/Expert/.test(m.uniqueName) && !m.name.startsWith('Primed'))) continue;
  for (const line of m.levelStats?.at(-1)?.stats ?? []) {
    const hit = LINE.exec(line.trim());
    if (hit) (power[m.name] ??= { rank: m.fusionLimit })[/** @type {'strength' | 'duration'} */ (hit[2].toLowerCase())] = Number(hit[1]);
  }
}

const sorted = (/** @type {string[]} */ names) => [...new Set(names)].sort();
const frames = sorted(underframe.warframes.map((/** @type {any} */ f) => f.name));
const mods = sorted(underframe.mods.filter((/** @type {any} */ m) => ['WARFRAME', 'AURA'].includes(m.Type)).map((/** @type {any} */ m) => m['Local Name']));
const wrapped = (/** @type {string[]} */ names) => names.map(n => JSON.stringify(n)).join(',').replace(/(.{1,110},)/g, '$1\n  ');

fs.writeFileSync(path.join(ROOT, 'src/data/frame-power.js'), `// @ts-check
// Generated by tools/build-frame-power.mjs. Don't edit by hand.

/** Mods that always change the panel's Strength or Duration, at max rank. @type {Record<string, {strength?: number, duration?: number, rank: number}>} */
export const POWER = {
${Object.entries(power).sort(([a], [b]) => a.localeCompare(b)).map(([name, p]) => `  ${JSON.stringify(name)}: ${JSON.stringify(p)},`).join('\n')}
};

/** Every frame's name, Primes apart. */
export const FRAME_NAMES = [
  ${wrapped(frames)}
];

/** Every Warframe and aura mod's name. */
export const FRAME_MOD_NAMES = [
  ${wrapped(mods)}
];
`);
console.log(Object.keys(power).length, 'with power,', frames.length, 'frames,', mods.length, 'mods');
