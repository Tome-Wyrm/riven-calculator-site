// Regenerates src/data/paths.js (internal weapon path → weapon name) from
// tools/data/internal_names.csv, for the inventory importer. Run by hand after editing the CSV:
//   node tools/build-paths.mjs

import { readFile, writeFile } from 'node:fs/promises';

const csv = await readFile(new URL('./data/internal_names.csv', import.meta.url), 'utf8');
/** @type {Record<string, string>} */
const map = {};
for (const line of csv.trim().split(/\r?\n/).slice(1)) {
  const [path, name] = line.slice(1, -1).split('","');
  map[path] = name;
}
const body = Object.entries(map).sort().map(([p, n]) => `  ${JSON.stringify(p)}: ${JSON.stringify(n)},`).join('\n');
await writeFile(new URL('../src/data/paths.js', import.meta.url), `// @ts-check
// GENERATED by tools/build-paths.mjs from tools/data/internal_names.csv. Don't edit by hand.
// Internal weapon path (a riven's "compat") → weapon name, as used in weapons.js.

/** @type {Record<string, string>} */
export const WEAPON_BY_PATH = {
${body}
};
`);
console.log(`Wrote ${Object.keys(map).length} paths`);
