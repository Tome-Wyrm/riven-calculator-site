// Regenerates src/data/brozime-picks.js: the riven Brozime recommends per weapon, from his Top Rivens
// notes (publish.obsidian.md/brozime, one note per category) and shown beside the community sheet's
// picks (tools/build-picks.mjs). One roll per weapon: whether it's spliced, three positives in his
// order of priority, and a negative ("Harmless" = any from his Harmless Riven Negatives rules).
//   node tools/build-brozime-picks.mjs [--offline]

import { writeFile } from 'node:fs/promises';
import { cachedText } from './lib/cache.mjs';
import { WEAPONS } from '../src/data/weapons.js';
import { STAT_BY_ID } from '../src/data/stats.js';

const RAW = 'https://publish-01.obsidian.md/access/e24d3ab0728206012febd6e4fcc69c6e/Public/Guides%20%26%20Builds/Guides/Rivens';
const SITE = 'https://publish.obsidian.md/brozime/Public/Guides+%26+Builds/Guides/Rivens';
const PAGES = ['Archguns', 'Companions', 'Melee', 'Rifle', 'Secondaries', 'Shotgun'];

/** His stat names (lower case) as stat ids. */
const STATS = {
  'status damage': 'statusDamage', multishot: 'multishot', 'ammo efficiency': 'ammoEfficiency',
  'critical damage': 'critDamage', 'crit damage': 'critDamage', 'critical chance': 'critChance', chance: 'critChance',
  'punch through': 'punchThrough', 'status duration': 'statusDuration', 'status chance': 'statusChance',
  'attack speed': 'fireRate', 'fire rate': 'fireRate', 'melee damage': 'damage', damage: 'damage',
  'initial combo': 'initialCombo', 'wind up speed': 'heavyWindup', 'parry angle': 'parryAngle',
  'weakpoint damage': 'weakpointDamage', 'weakpoint critical': 'weakpointCrit', 'weakpoint critical chance': 'weakpointCrit',
  heat: 'heat', cold: 'cold', toxin: 'toxin', electric: 'electricity', viral: 'viral', corrosive: 'corrosive',
  gas: 'gas', blast: 'blast', impact: 'impact', puncture: 'puncture', slash: 'slash',
};
/** Rows for something that isn't one weapon here. */
const SKIP = new Set(['Contagion Zaw']);
const KNOWN = new Map(WEAPONS.map(w => [w[0].toLowerCase(), w[0]]));

/** @typedef {{splice: boolean, positives: string[][], negative: string | null, notes: string[], page: string}} Entry */
/** @type {Record<string, Entry>} */
const out = {};
const problems = [];

for (const page of PAGES) {
  const { data: note } = await cachedText(`brozime-top-rivens-${page.toLowerCase()}`, 'md', `${RAW}/Top%20Rivens/${page}.md`,
    { validate: t => (t.includes('| Weapon') && t.includes('Splice?') ? null : 'no riven table') });
  // "\|" is a pipe inside a cell (the wiki link's label).
  const [, , ...rows] = note.split('\n').filter(l => l.startsWith('|')).map(l => l.replace(/\\\|/g, '\u0001').split('|').slice(1, -1).map(c => c.trim()));
  for (const [name, splice, p1, p2, p3, neg] of rows) {
    if (SKIP.has(name)) continue;
    const weapon = KNOWN.get(name.toLowerCase());
    if (!weapon) { problems.push(`${page}: no weapon "${name}"`); continue; }
    /** @type {string[]} */
    const notes = [];
    /** A cell's stats: "Critical Damage/Chance" is two; an <abbr> carries a hover note. @param {string} cell */
    const statsOf = cell => {
      const abbr = cell.match(/<abbr title="([^"]*)">([^<]*)<\/abbr>/);
      const text = (abbr ? abbr[2] : cell.replace(/<[^>]*>/g, '')).trim();
      if (abbr) notes.push(`${text}: ${abbr[1]}`);
      if (!text || text === 'N/A') return [];
      return text.split('/').map(s => {
        const id = STATS[/** @type {keyof typeof STATS} */ (s.trim().toLowerCase())];
        if (!id || !STAT_BY_ID[id]) problems.push(`${page}, ${name}: unknown stat "${s}"`);
        return id;
      });
    };
    const positives = [p1, p2, p3].map(statsOf).filter(s => s.length);
    const negative = /Harmless/.test(neg) ? null : statsOf(neg)[0];
    if (!/^(Yes|No)$/.test(splice)) problems.push(`${page}, ${name}: Splice? is "${splice}"`);
    out[weapon] = { splice: splice === 'Yes', positives, negative, notes, page };
  }
}
if (problems.length) throw new Error(`Brozime's Top Rivens notes don't read cleanly:\n  ${problems.join('\n  ')}`);

const date = new Date().toISOString().slice(0, 10);
await writeFile(new URL('../src/data/brozime-picks.js', import.meta.url), `// @ts-check
// GENERATED by tools/build-brozime-picks.mjs on ${date} from Brozime's Top Rivens notes. Don't edit by hand.
// The riven he recommends per weapon: whether it's spliced (then the first positive is the spliced
// stat), the positives in his order of priority (stat ids; a slot with two is either), the negative
// (null = any harmless one, by his rules), his hover notes, and the note it's on.

export const BROZIME_PICKS_UPDATED = '${date}';
/** The notes' folder; a weapon's note is \`\${BROZIME_PICKS_SOURCE}/Top+Rivens/\${page}\`. */
export const BROZIME_PICKS_SOURCE = '${SITE}';

/** @type {Record<string, {splice: boolean, positives: string[][], negative: string | null, notes: string[], page: string}>} */
export const BROZIME_PICKS = {
${Object.keys(out).sort().map(k => `  ${JSON.stringify(k)}: ${JSON.stringify(out[k])},`).join('\n')}
};
`);
console.log(`Brozime's picks for ${Object.keys(out).length} weapons`);
