// Regenerates src/data/incarnons.js (each incarnon gun's evolution perks, as the damage model takes
// them) from Underframe's incarnon data. Run by hand when incarnons change:
//   node tools/build-incarnons.mjs [--offline]
// Each perk keeps its name, its text, and the effects the model applies (src/incarnon.js). Effects
// that depend on a condition (on headshot, while sliding, per Electricity proc…) are left out, apart
// from the non-critical hit bonus (Devouring / Devastating Attrition), which is a chance, not a
// condition; a perk whose damage effects are all left out says so ("not modelled").

import { writeFile } from 'node:fs/promises';
import { cachedJson } from './lib/cache.mjs';
import { WEAPON_STATS } from '../src/data/weapon-stats.js';

const { data: uf } = await cachedJson('underframe', 'https://www.underframe.site/api/data', {
  validate: d => (Array.isArray(d?.incarnons) ? null : 'no incarnons'),
});

/**
 * Underframe's upgrade types → the model's perk effects. Base stats are added to the weapon's own
 * (crit and status chance in points, crit multiplier in x, multishot and magazine in units, base
 * damage to each attack's total); the rest stack with mods of the same kind.
 */
const KIND = {
  WEAPON_BASE_DAMAGE: 'baseDamage',
  WEAPON_CRITICAL_CHANCE: 'cc',
  WEAPON_STATUS_CHANCE: 'sc',
  WEAPON_CRITICAL_MULTIPLIER: 'cd',
  WEAPON_MULTISHOT: 'ms',
  WEAPON_MAGAZINE_CAPACITY: 'mag',
  WEAPON_CRITICAL_CHANCE_FLAT: 'ccFlat',
  WEAPON_HEADSHOT_MULTIPLIER: 'hs',
  WEAPON_HEADSHOT_DAMAGE: 'hs',
  WEAPON_FIRE_RATE: 'fireRate',
  WEAPON_RELOAD_SPEED: 'reloadSpeed',
};
/** Damage-related effects the model doesn't take (to flag a perk as not modelled). */
const DAMAGE = /DAMAGE|CRIT|STATUS|MULTISHOT|FIRE_RATE|PROC|ARMOR|VULNERAB/;

/** @param {string} text */
const clean = text => text.replace(/^Perk \d+:\s*/, '').replace(/\s+([.,])/g, '$1').trim();

/**
 * A perk's effects. Status chance per form: Underframe's StatusChanceByForm, or the text's "+2.5% per
 * projectile, +10% for Incarnon Form".
 * @param {any[]} stats @param {any[]} cond @param {string} text
 */
function effects(stats, cond, text) {
  const out = [];
  let skipped = false;
  for (const s of stats) {
    const kind = KIND[/** @type {keyof typeof KIND} */ (s.UpgradeType)];
    if (!kind) { if (DAMAGE.test(s.UpgradeType)) skipped = true; continue; }
    const e = { kind, value: s.Value };
    if (kind === 'sc') {
      const byForm = s.StatusChanceByForm;
      const perProj = /\+([\d.]+)% per projectile.*?\+([\d.]+)% for Incarnon Form/i.exec(text);
      if (byForm) Object.assign(e, { value: byForm.normal, incarnon: byForm.incarnon });
      else if (perProj) Object.assign(e, { value: Number(perProj[1]) / 100, incarnon: Number(perProj[2]) / 100 });
    }
    out.push(e);
  }
  for (const s of cond) {
    if (s.UpgradeType === 'WEAPON_NON_CRIT_DAMAGE_MULTIPLIER') {
      const chance = /(\d+)% chance/i.exec(s.OriginalValue ?? text);
      out.push({ kind: 'nonCrit', value: s.Value, chance: chance ? Number(chance[1]) / 100 : 1 });
    } else if (DAMAGE.test(s.UpgradeType)) skipped = true;
  }
  return { out, skipped };
}

/** @type {Record<string, {evolution: number, perks: {name: string, text: string, effects: any[], partly?: boolean}[]}[]>} */
const INCARNONS = {};
/** @type {Record<string, {hits: number, any: boolean, ammo: number}>} */
const CHARGE = {};
let modelled = 0;
for (const w of uf.incarnons) {
  if (!WEAPON_STATS[w.name] || WEAPON_STATS[w.name].melee) continue;   // guns only (melee perks aren't modelled)
  if (w.charge_count && w.incarnon_max_ammo) CHARGE[w.name] = { hits: w.charge_count, any: w.charge_type === 'Hit', ammo: w.incarnon_max_ammo };
  const evolutions = [];
  for (let n = 2; n <= 5; n++) {
    const evo = w.evolutions[`evolution_${n}`];
    if (!evo) continue;
    const perks = [];
    for (let p = 1; p <= 3; p++) {
      const desc = evo[`perk_${p}_description`];
      if (!desc) continue;
      const text = clean(desc);
      const { out, skipped } = effects(evo[`perk_${p}_stats`] ?? [], evo[`perk_${p}_conditional_stats`] ?? [], text);
      const name = text.split(':')[0].trim();
      perks.push({ name, text: text.slice(name.length + 1).trim(), effects: out, ...(skipped ? { partly: true } : {}) });
      if (out.length) modelled++;
    }
    evolutions.push({ evolution: n, perks });
  }
  INCARNONS[w.name] = evolutions;
}

const date = new Date().toISOString().slice(0, 10);
await writeFile(new URL('../src/data/incarnons.js', import.meta.url), `// @ts-check
// GENERATED by tools/build-incarnons.mjs on ${date}, from Underframe's incarnon data. Don't edit by hand.
// Per incarnon gun: evolutions II–V, each with its perks (name, text, the effects the model applies:
// src/incarnon.js). partly: the perk also does something conditional the model leaves out.

/** @typedef {{kind: string, value: number, incarnon?: number, chance?: number}} PerkEffect */
/** @typedef {{name: string, text: string, effects: PerkEffect[], partly?: boolean}} Perk */

/** @type {Record<string, {evolution: number, perks: Perk[]}[]>} */
export const INCARNONS = {
${Object.entries(INCARNONS).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n')}
};

/**
 * What fills each gun's gauge and what it holds: hits to fill it (weak point hits, or any hit),
 * ammo in the Incarnon Form.
 * @type {Record<string, {hits: number, any: boolean, ammo: number}>}
 */
export const INCARNON_CHARGE = {
${Object.entries(CHARGE).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n')}
};
`);
console.log(`Wrote ${Object.keys(INCARNONS).length} incarnon guns, ${modelled} perks with modelled effects`);
