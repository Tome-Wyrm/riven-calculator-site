// Regenerates src/data/allowlist.js (the MD5 hashes of the names that may open Recommended rolls)
// from tools/data/allowlist.txt, which is git-ignored: the names never leave this machine. Each line
// is name=hash; a blank hash is computed and written back, and a hash that doesn't match its name
// stops the build. Run by hand after editing the list:
//   node tools/build-allowlist.mjs

import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const listUrl = new URL('./data/allowlist.txt', import.meta.url);
const text = await readFile(listUrl, 'utf8');
const md5 = (/** @type {string} */ s) => createHash('md5').update(s, 'utf8').digest('hex');

const hashes = new Set();
let filled = 0;
const lines = text.split(/\r?\n/).map(line => {
  const m = /^([^#=][^=]*)=([0-9a-f]*)\s*$/i.exec(line);
  if (!m) return line;
  const [, name, given] = m;
  const hash = md5(name);
  if (given && given.toLowerCase() !== hash) throw new Error(`${name}: the hash given doesn't match (expected ${hash})`);
  if (!given) filled++;
  hashes.add(hash);
  return `${name}=${hash}`;
});
if (filled) await writeFile(listUrl, lines.join('\n'));

await writeFile(new URL('../src/data/allowlist.js', import.meta.url), `// @ts-check
// GENERATED by tools/build-allowlist.mjs from a git-ignored list. Don't edit by hand.
// MD5 hashes of the names that may open Recommended rolls (src/ui/gate.js).

export const ALLOWED = new Set(${JSON.stringify([...hashes].sort(), null, 2).replace(/\n/g, '\n')});
`);
console.log(`${hashes.size} names (${filled} hashes filled in)`);
